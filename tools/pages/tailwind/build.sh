#!/bin/sh
# Regenerate the prebuilt Tailwind CSS used by the Research IDE and the Circuit-SETH explorer.
# Needs Node.js and npm registry access. Afterwards run `make -C Research_IDE lock-ide` and the tests.
set -eu
cd "$(dirname "$0")/../../.."
TAILWIND=${TAILWIND:-"npx --yes tailwindcss@3.4.19"}

build() {
  config=$1
  output=$2
  tmp="$output.tmp"
  {
    echo "/* Generated by tools/pages/tailwind/build.sh from $config with Tailwind CSS v3.4.19; do not edit. */"
    $TAILWIND -c "tools/pages/tailwind/$config" -i tools/pages/tailwind/input.css --minify
    echo
  } > "$tmp"
  mv "$tmp" "$output"
}

build research-ide.config.cjs Research_IDE/ide-tailwind.css
build explorer.config.cjs site/circuit-seth/explorer-tailwind.css
