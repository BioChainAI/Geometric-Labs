"""Check original reference bytes while allowing two navigation documents to evolve.

The Wave 00 snapshot remains historical and is never regenerated by this check.
Every recorded file remains immutable by default. The only exceptions are the
root overview and the paper-intake overview, whose archive links changed in PR #7.
Scientific source, tests, vectors, specifications and root tooling remain frozen.
"""
import hashlib
from pathlib import Path


MUTABLE_DOCUMENTATION = {
    'README.md': 'Project navigation and links to newly integrated research areas.',
    'docs/papers/README.md': 'Paper intake navigation now links to the central research archive.',
}


def preservation_errors(root: Path, snapshot: dict) -> list[str]:
    errors = []
    for name, expected in snapshot['sha256'].items():
        if name in MUTABLE_DOCUMENTATION:
            continue
        path = root / name
        if not path.is_file():
            errors.append(f'{name}: original reference file missing')
        elif hashlib.sha256(path.read_bytes()).hexdigest() != expected:
            errors.append(f'{name}: original reference bytes changed')
    return errors
