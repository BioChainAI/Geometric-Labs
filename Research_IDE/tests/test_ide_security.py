"""IDE page contracts: pinned CDN files with integrity, an exact CSP, keys kept out of storage,
Markdown sanitised before display and PDF.js options. Static checks on index.html; no network."""
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import unittest
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
PAGE = (ROOT / "index.html").read_text()
LOCK = json.loads((ROOT / "ide.lock.json").read_text())
PINNED = re.compile(r"https://cdn\.jsdelivr\.net/npm/[a-z0-9._-]+@(\d+)\.(\d+)\.(\d+)/[^?#\s]+")
EXPECTED_CONNECT = {"'self'", "https://generativelanguage.googleapis.com", "https://openrouter.ai",
                    "http://localhost:11434", "http://127.0.0.1:11434"}


class Tags(HTMLParser):
    def __init__(self):
        super().__init__(); self.external = []; self.csp = []; self.order = []
    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "meta" and (attrs.get("http-equiv") or "").lower() == "content-security-policy":
            self.csp.append(attrs["content"])
        url = attrs.get("src") if tag == "script" else attrs.get("href") if tag == "link" else None
        if tag == "script":
            self.order.append(url or "inline")
        if url and urlsplit(url).scheme:
            self.external.append(dict(attrs, tag=tag, url=url))


def page_tags(text=PAGE):
    parser = Tags(); parser.feed(text); return parser


def csp(text=PAGE):
    policies = page_tags(text).csp
    if len(policies) != 1:
        raise AssertionError("expected one CSP meta, found %d" % len(policies))
    return {part.split()[0]: part.split()[1:] for part in policies[0].split(";") if part.split()}


def external_problems(text):
    problems = []
    for item in page_tags(text).external:
        if not PINNED.fullmatch(item["url"]):
            problems.append("not an exact-version jsDelivr file: " + item["url"])
        if not re.fullmatch(r"sha384-[A-Za-z0-9+/]{64}", item.get("integrity") or ""):
            problems.append("missing sha384 integrity: " + item["url"])
        if item.get("crossorigin") != "anonymous":
            problems.append("missing crossorigin=anonymous: " + item["url"])
    return problems


class CdnPins(unittest.TestCase):
    def test_every_external_file_is_pinned_with_integrity(self):
        self.assertTrue(page_tags().external)
        self.assertEqual(external_problems(PAGE), [])

    def test_check_rejects_unpinned_or_unhashed_tags(self):
        for tag in ('<script src="https://cdn.jsdelivr.net/npm/marked/marked.min.js"></script>',
                    '<script src="https://unpkg.com/lucide@latest"></script>',
                    '<script src="https://cdn.jsdelivr.net/npm/marked@18.1.1/lib/marked.umd.js" crossorigin="anonymous"></script>',
                    '<link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/katex@0.18.11/dist/katex.min.css" integrity="sha384-' + 'A' * 64 + '">'):
            self.assertTrue(external_problems(tag), tag)

    def test_lock_records_exactly_the_page_dependencies(self):
        page = {(i["url"], i["integrity"]) for i in page_tags().external}
        lock = {(d["url"], d["integrity"]) for d in LOCK["runtime_dependencies"]}
        self.assertEqual(page, lock)

    def test_no_runtime_play_cdn_or_floating_versions(self):
        for needle in ("cdn.tailwindcss.com", "unpkg.com", "cdnjs.cloudflare.com", "@latest", "npm/marked/"):
            self.assertNotIn(needle, PAGE)
        self.assertIn('<link rel="stylesheet" href="ide-tailwind.css">', PAGE)
        self.assertTrue((ROOT / "ide-tailwind.css").read_text().startswith("/* Generated by tools/pages/tailwind/build.sh"))
        self.assertIn("ide-tailwind.css", {a["file"] for a in LOCK["assets"]})

    def test_pdfjs_version_and_options(self):
        versions = {tuple(map(int, m.groups())) for m in PINNED.finditer(PAGE) if "/pdfjs-dist@" in m.group(0)}
        self.assertEqual(len(versions), 1)
        self.assertGreaterEqual(versions.pop(), (4, 2, 67))
        call = PAGE[PAGE.index("window.pdfjsLib.getDocument({"):][:200]
        self.assertIn("isEvalSupported: false", call)
        self.assertNotIn("disableWorker", PAGE)
        modules = [i for i in page_tags().external if "/pdfjs-dist@" in i["url"]]
        self.assertEqual({i.get("type") for i in modules}, {"module"})
        self.assertTrue(any(i["url"].endswith("/pdf.worker.min.mjs") for i in modules))
        # PDF.js 4.10.38 needs Promise.withResolvers; both PDF paths say which browsers are required.
        self.assertEqual(PAGE.count("if (typeof Promise.withResolvers !== 'function') throw new Error(PDF_BROWSER_NOTE"), 2)
        self.assertIn("Chrome or Edge 119, Firefox 121, Safari 17.4", PAGE)

    def test_sanitiser_loads_before_the_application_script(self):
        order = page_tags().order
        purify = next(i for i, url in enumerate(order) if "/dompurify@" in url)
        self.assertLess(purify, order.index("ide-safety.js"))
        self.assertLess(order.index("ide-safety.js"), order.index("inline"))


class ContentSecurityPolicy(unittest.TestCase):
    def test_policy_lists_exactly_the_pinned_files_in_use(self):
        policy = csp()
        files = lambda tag: {i["url"] for i in page_tags().external if i["tag"] == tag}
        https = lambda d: {s for s in policy[d] if s.startswith("https://")}
        self.assertEqual(https("script-src"), files("script"))
        self.assertEqual(https("style-src"), files("link"))
        # KaTeX's stylesheet loads its fonts from the fonts/ folder beside it.
        self.assertEqual(https("font-src"), {url.rsplit("/", 1)[0] + "/fonts/" for url in files("link")})
        for directive in ("script-src", "style-src", "font-src"):
            self.assertTrue(all(urlsplit(s).path not in ("", "/") for s in https(directive)), directive)
        self.assertEqual(set(policy["connect-src"]), EXPECTED_CONNECT)
        for directive in ("default-src", "object-src", "base-uri", "form-action", "worker-src"):
            self.assertEqual(policy[directive], ["'none'"], directive)

    def test_policy_never_allows_string_evaluation_or_wildcards(self):
        for directive, sources in csp().items():
            refused = {"'unsafe-eval'", "*", "https:", "http:"}
            if directive not in ("img-src", "font-src"):
                refused.add("data:")
            self.assertFalse(refused & set(sources), directive)
        self.assertNotIn("frame-ancestors", csp())  # ignored in a meta element


class ApiKeysInMemoryOnly(unittest.TestCase):
    def test_no_key_reaches_browser_storage(self):
        self.assertEqual(PAGE.count("localStorage"), 1)  # only inside browserStorage()
        for item in ("gl_gemini_key", "gl_openrouter_key"):
            self.assertNotIn(item, PAGE)
        writes = re.findall(r"writePreference\('([a-z_]+)'", PAGE)
        self.assertEqual(set(writes), {"gl_ai_provider", "gl_gemini_model", "gl_ollama_url"})
        self.assertNotIn("sessionStorage", PAGE)
        self.assertNotIn("indexedDB", PAGE)
        self.assertNotIn("document.cookie", PAGE)

    def test_old_keys_are_removed_on_load_and_the_user_is_told(self):
        self.assertIn("const removedStoredKeyItems = IdeSafety.removeStoredApiKeys(browserStorage());", PAGE)
        self.assertIn("if (removedStoredKeyItems.length > 0) {", PAGE)
        self.assertIn("kept in this tab's memory only", PAGE)
        safety = (ROOT / "ide-safety.js").read_text()
        self.assertIn("['gl_gemini_key', 'gl_openrouter_key']", safety)

    def test_gemini_key_goes_in_a_header(self):
        self.assertNotRegex(PAGE, r"[?&]key=")
        self.assertEqual(PAGE.count("generativelanguage.googleapis.com"), 1)  # the CSP only
        self.assertEqual(PAGE.count("const request = IdeSafety.geminiRequest("), 2)
        self.assertIn("fetch(request.url, request.init)", PAGE)
        self.assertIn("headers['x-goog-api-key'] = apiKey", (ROOT / "ide-safety.js").read_text())


class UntrustedTextRendering(unittest.TestCase):
    def test_markdown_preview_is_sanitised(self):
        self.assertIn("previewPane.innerHTML = IdeSafety.renderMarkdown(rawMarkdown, { marked: window.marked, purify: window.DOMPurify });", PAGE)
        self.assertNotIn("marked.parse(", PAGE)
        self.assertEqual(len(re.findall(r"previewPane\.innerHTML\s*=", PAGE)), 2)  # empty-state template + sanitised output

    def test_latex_spans_inside_templates_are_escaped(self):
        # Formula text placed into HTML templates (as element text before KaTeX runs) is escaped.
        self.assertEqual(re.findall(r">\s*\$\$\$\{(?!escapeHtml\()", PAGE), [])
        self.assertEqual(len(re.findall(r">\s*\$\$\$\{escapeHtml\((f|st)\.latex\)\}\$\$", PAGE)), 2)
        self.assertNotIn("copyToClipboard('${escapeAttr(f.latex)}')", PAGE)
        self.assertIn('onclick="copyFormulaTex(${f.idx})"', PAGE)


